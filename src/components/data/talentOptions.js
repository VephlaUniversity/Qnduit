// Match aliases without storing duplicate canonical choices.
export function matchesTalentOption(option, query) {
  const normalize = value => value.toLowerCase().replace(/[-/]+/g, " ").replace(/\s+/g, " ").trim();
  const terms = normalize(query).split(" ").filter(Boolean);
  const searchableText = normalize([option.value, ...(option.aliases || [])].join(" "));
  return terms.every(term => searchableText.includes(term));
}
